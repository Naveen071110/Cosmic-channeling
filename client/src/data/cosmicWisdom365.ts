/**
 * Returns the contemplative wisdom assigned to today's Julian day of the year (0 to 364).
 */
export function getDailyWisdom(date: Date = new Date()): DailyCosmicWisdom {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay) % 365;
  return COSMIC_WISDOM_365[Math.max(0, Math.min(364, dayOfYear))];
}

/**
 * Returns a random wisdom entry from the 365-day archive for on-demand contemplation.
 */
export function getRandomWisdom(): DailyCosmicWisdom {
  const idx = Math.floor(Math.random() * COSMIC_WISDOM_365.length);
  return COSMIC_WISDOM_365[idx];
}

/**
 * Returns wisdom entry by explicit day index.
 */
export function getWisdomByDay(dayIndex: number): DailyCosmicWisdom {
  const safeIdx = Math.abs(dayIndex) % 365;
  return COSMIC_WISDOM_365[safeIdx];
}
